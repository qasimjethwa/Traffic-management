import type { DataKind, Freshness } from '../../types/provenance';

const KIND_LABEL: Record<DataKind, string> = {
  OBSERVED: 'Observed',
  ESTIMATED: 'Estimated',
  FORECAST: 'Forecast',
  SIMULATED: 'Simulated',
};

const KIND_HINT: Record<DataKind, string> = {
  OBSERVED: 'Measured in the real world',
  ESTIMATED: 'Computed by an external model from real inputs — not a measurement',
  FORECAST: 'Prediction from an evaluated model',
  SIMULATED: 'Generated by the demo simulation — not real traffic',
};

/** Labels a value's provenance. Every real/simulated value in the UI should carry one. */
export function DataBadge({ kind, freshness, title }: { kind: DataKind | 'UNAVAILABLE'; freshness?: Freshness | 'unavailable' | 'not_stored'; title?: string }) {
  if (kind === 'UNAVAILABLE') {
    return (
      <span className="dbadge" data-kind="UNAVAILABLE" title={title ?? 'No real data is available for this value'}>
        Unavailable
      </span>
    );
  }
  return (
    <span className="dbadge" data-kind={kind} title={title ?? KIND_HINT[kind]}>
      {KIND_LABEL[kind]}
      {freshness === 'stale' && <em className="dbadge-stale"> · stale</em>}
    </span>
  );
}

export function FreshnessPill({ value }: { value: string }) {
  const tone = value === 'fresh' ? 'ok' : value === 'stale' ? 'warn' : value === 'unavailable' ? 'crit' : 'mute';
  return <span className={`pill ${tone}`}>{value.replace('_', ' ')}</span>;
}
